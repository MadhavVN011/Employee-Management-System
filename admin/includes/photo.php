<?php
function store_photo($upload) {
    if ($upload === null || (is_array($upload) && ($upload['error'] ?? null) === UPLOAD_ERR_NO_FILE)) {
        return null;
    }
    if (!is_array($upload) || ($upload['error'] ?? null) !== UPLOAD_ERR_OK ||
        !isset($upload['name'], $upload['tmp_name']) || !is_string($upload['name']) ||
        !is_string($upload['tmp_name']) || !is_uploaded_file($upload['tmp_name'])) {
        throw new InvalidArgumentException('Unable to upload the photo. Choose an image up to 5 MB.');
    }
    $size = filesize($upload['tmp_name']);
    if (!$size || $size > 5 * 1024 * 1024) {
        throw new InvalidArgumentException('Choose an image up to 5 MB.');
    }
    $types = array('image/jpeg' => 'jpg', 'image/png' => 'png', 'image/gif' => 'gif', 'image/webp' => 'webp');
    $extension = strtolower(pathinfo($upload['name'], PATHINFO_EXTENSION));
    $mime = (new finfo(FILEINFO_MIME_TYPE))->file($upload['tmp_name']);
    $image = @getimagesize($upload['tmp_name']);
    if (!in_array($extension, array('jpg', 'jpeg', 'png', 'gif', 'webp'), true) ||
        !isset($types[$mime]) || !$image || ($image['mime'] ?? '') !== $mime ||
        ($extension === 'jpeg' ? 'jpg' : $extension) !== $types[$mime]) {
        throw new InvalidArgumentException('Choose a valid JPEG, PNG, GIF, or WebP image.');
    }
    $filename = bin2hex(random_bytes(16)).'.'.$types[$mime];
    if (!move_uploaded_file($upload['tmp_name'], __DIR__.'/../../images/'.$filename)) {
        throw new InvalidArgumentException('Unable to save the photo. Please try again.');
    }
    return $filename;
}

function discard_photo($filename) {
    // Only remove a new file generated by store_photo, never a shared old photo.
    if (is_string($filename) && preg_match('/^[a-f0-9]{32}\.(?:jpg|png|gif|webp)$/', $filename)) {
        @unlink(__DIR__.'/../../images/'.$filename);
    }
}
